def read_stat(path: str) -> tuple[str, int, int, str]:
    with open(path) as f:
        s = f.read()
    comm = s[s.index("(") + 1: s.rindex(")")]
    rest = s[s.rindex(")") + 2:].split()
    return comm, int(rest[11]) + int(rest[12]), int(rest[2]), rest[0]   # comm, utime+stime, pgrp, state


def group_pids(pgid: int, include_zombies: bool = False) -> list[tuple[int, str]]:
    out = []
    for d in os.listdir("/proc"):
        if not d.isdigit():
            continue
        try:
            comm, _, pgrp, state = read_stat(f"/proc/{d}/stat")
        except (OSError, ValueError, IndexError):
            continue
        if pgrp == pgid and (include_zombies or state != "Z"):
            out.append((int(d), comm))
    return out


def kill_group(pgid: int, sig: int = signal.SIGKILL) -> bool:
    """Send ``sig`` to one process group (ours); False if the group no longer exists."""
    try:
        os.killpg(pgid, sig)
        return True
    except ProcessLookupError:
        return False


#: process names of a Gazebo server / GUI (``gz sim`` runs inside the ruby interpreter)
GZ_COMMS = ("gz", "ruby", "ruby3.2", "gz-sim-server", "gz-sim-gui")


def is_gz_process(pid: int, comm: str | None = None) -> bool:
    """True for a gz sim server/GUI process: its name is gz/ruby*, or its command line is
    ``[ruby ...] gz sim ...``."""
    if comm is None:
        try:
            comm = read_stat(f"/proc/{pid}/stat")[0]
        except (OSError, ValueError, IndexError):
            return False
    if comm in GZ_COMMS or comm.startswith("ruby"):
        return True
    try:
        argv = open(f"/proc/{pid}/cmdline", "rb").read().split(b"\0")
    except OSError:
        return False
    names = [os.path.basename(a.decode("utf-8", "replace")) for a in argv[:3]]
    return "gz" in names and b"sim" in argv[:4]


def gz_pids(pgid: int) -> list[int]:
    """gz sim processes (server / GUI) in one process group."""
    return [p for p, c in group_pids(pgid) if is_gz_process(p, c)]


def mem_status(pid: int) -> dict:
    r = {}
    try:
        with open(f"/proc/{pid}/status") as f:
            for line in f:
                k, _, v = line.partition(":")
                if k in ("VmRSS", "VmHWM", "Threads", "VmSize"):
                    r[k] = int(v.split()[0])
    except OSError:
        pass
    return r


def proc_ticks(pid: int) -> int | None:
    try:
        return read_stat(f"/proc/{pid}/stat")[1]
    except (OSError, ValueError, IndexError):
        return None


def threads_cpu(pid: int) -> dict:
    res = {}
    try:
        for tid in os.listdir(f"/proc/{pid}/task"):
            try:
                comm, ticks, _, _ = read_stat(f"/proc/{pid}/task/{tid}/stat")
                res[int(tid)] = (comm, ticks)
            except (OSError, ValueError, IndexError):
                pass
    except OSError:
        pass
    return res


def renderer_libs(pids: list[int]) -> dict:
    """GL driver libraries mapped by each process (race-free renderer evidence)."""
    ev = {}
    keys = ("libd3d12", "libdxcore", "swrast", "llvmpipe", "libgallium", "libnvidia", "libEGL_mesa", "libGLX_mesa")
    for p in pids:
        try:
            with open(f"/proc/{p}/maps") as f:
                libs = sorted({ln.split()[-1].rsplit("/", 1)[-1] for ln in f if any(k in ln for k in keys)})
            if libs:
                ev[str(p)] = libs
        except OSError:
            pass
    flat = [x for v in ev.values() for x in v]
    return {"libs": ev, "d3d12": any("libd3d12" in x for x in flat),
            "software": any(("swrast" in x) or ("llvmpipe" in x) for x in flat)}


def system_busy_ticks() -> int | None:
    """Busy jiffies of all CPUs (/proc/stat: user+nice+system+irq+softirq+steal)."""
    try:
        with open("/proc/stat") as f:
            v = [int(x) for x in f.readline().split()[1:]]
        return v[0] + v[1] + v[2] + v[5] + v[6] + (v[7] if len(v) > 7 else 0)
    except (OSError, ValueError, IndexError):
        return None


def all_proc_ticks() -> dict[int, tuple[str, int, int]]:
    """pid -> (comm, utime+stime, pgrp) for every process."""
    out = {}
    for d in os.listdir("/proc"):
        if d.isdigit():
            try:
                comm, ticks, pgrp, _ = read_stat(f"/proc/{d}/stat")
                out[int(d)] = (comm, ticks, pgrp)
            except (OSError, ValueError, IndexError):
                pass
    return out


def contention(t0: dict, t1: dict, busy0: int | None, busy1: int | None, dt: float,
               own_pgid: int | set | None) -> dict:
    """CPU used during a window by the whole machine, by our process group(s) and by everything else.

    ``other_procs_*``: processes outside our group(s) alive at the end of the window; a process that
    STARTED during the window counts with all its CPU time (before, such processes - e.g. another
    agent's job launched mid-window - were invisible). Processes that started and ended inside the
    window only show in ``other_busy_cores`` = system busy - our group(s) - this tool.
    """
    res: dict = {}
    me = os.getpid()
    own_set = set(own_pgid) if isinstance(own_pgid, (set, frozenset, list, tuple)) else {own_pgid}
    own = 0
    other = []
    for pid, (comm, ticks, pgrp) in t1.items():
        if pid == me:
            continue
        new = pid not in t0
        d = ticks if new else ticks - t0[pid][1]
        if pgrp in own_set:
            own += max(d, 0)
            continue
        if d > 0:
            other.append((round(100.0 * d / CLK / dt, 1), pid, comm, new))
    other.sort(reverse=True)
    res["other_procs_cpu_pct"] = round(sum(o[0] for o in other), 1)
    res["other_procs_top"] = other[:6]
    res["own_group_cpu_pct"] = round(100.0 * own / CLK / dt, 1) if dt > 0 else None
    if busy0 is not None and busy1 is not None and dt > 0:
        # tick-sampled: exact for CPU hogs, but it under-counts gz's 1 kHz sleep/wake pattern (WSL2,
        # measured: 0.41 busy cores while the server alone used 0.68), so it may be < own_group
        res["system_busy_cores"] = round((busy1 - busy0) / CLK / dt, 2)
    return res


def load_point(server_pid: int | None, t: float | None = None) -> tuple:
    """One load sample: (time, system busy ticks, server ticks, {pid: (comm, ticks, pgrp)})."""
    return (clock() if t is None else t, system_busy_ticks(), proc_ticks(server_pid) if server_pid else None,
            all_proc_ticks())


def contention_series(points: list[tuple], stats: list[tuple], bin_s: float = 2.0, own_pgids=()) -> dict:
    """RTF against other processes' CPU use in consecutive bins of a window.

    ``points``: ``load_point`` samples (time, busy ticks, server ticks, process table); ``stats``:
    rows (time, sim, real, ...) on the same time base. Other processes' CPU comes from per-process
    tick deltas between consecutive samples (a process first seen counts with all its ticks; one
    that lives shorter than the sample period is missed), excluding ``own_pgids``. Returns the
    bins, the top other consumers and the RTF over the bins in which other processes used less
    than 1 core (``rtf_other_lt_1core``) - a diagnostic of contention, not a criterion.
    """
    bins: list[dict] = []
    if len(points) < 2 or len(stats) < 2:
        return {"bins": bins}
    own = set(own_pgids or ())
    by_comm: dict[str, float] = {}
    step_other = []
    for p0, p1 in zip(points[:-1], points[1:]):
        o = 0
        if p0[3] is not None and p1[3] is not None:
            for pid, (comm, ticks, pgrp) in p1[3].items():
                if pgrp in own or pid == os.getpid():
                    continue
                d = ticks - p0[3][pid][1] if pid in p0[3] else ticks
                if d > 0:
                    o += d
                    by_comm[comm] = by_comm.get(comm, 0) + d
        step_other.append(o)
    i0 = 0
    for i in range(1, len(points)):
        if points[i][0] - points[i0][0] < bin_s and i < len(points) - 1:
            continue
        a, b = points[i0], points[i]
        dt = b[0] - a[0]
        S = [s for s in stats if a[0] <= s[0] <= b[0]]
        row = {"t0": round(a[0], 2), "dt": round(dt, 2)}
        if dt > 0:
            if None not in (a[1], b[1]):
                row["busy_cores"] = round((b[1] - a[1]) / CLK / dt, 2)
            if None not in (a[2], b[2]):
                row["server_cores"] = round((b[2] - a[2]) / CLK / dt, 2)
            row["other_cores"] = round(sum(step_other[i0:i]) / CLK / dt, 2)
        if len(S) >= 2 and S[-1][2] > S[0][2]:
            row["sim_s"] = S[-1][1] - S[0][1]
            row["real_s"] = S[-1][2] - S[0][2]
            row["rtf"] = round(row["sim_s"] / row["real_s"], 4)
        bins.append(row)
        i0 = i
    q = [r for r in bins if r.get("other_cores") is not None and r["other_cores"] < 1.0 and "rtf" in r]
    T = points[-1][0] - points[0][0]
    out = {"bin_s": bin_s, "bins": bins, "n_bins": len(bins), "n_bins_other_lt_1core": len(q),
           "other_top": sorted(((round(100.0 * v / CLK / T, 1), k) for k, v in by_comm.items()), reverse=True)[:6]
           if T > 0 else []}
    if q:
        out["rtf_other_lt_1core"] = round(sum(r["sim_s"] for r in q) / sum(r["real_s"] for r in q), 4)
    oc = [r["other_cores"] for r in bins if r.get("other_cores") is not None]
    if oc:
        out["other_cores_mean"] = round(float(np.mean(oc)), 2)
        out["other_cores_max"] = round(float(np.max(oc)), 2)
    rr = [r["rtf"] for r in bins if "rtf" in r]
    if rr:
        out["rtf_bin_min"] = round(float(np.min(rr)), 4)
    return out


def _ppid(pid: int) -> int:
    with open(f"/proc/{pid}/stat") as f:
        s = f.read()
    return int(s[s.rindex(")") + 2:].split()[1])   # field 4 = parent pid


def _own_lineage() -> set[int]:
    """This process and its ancestors (their command lines may mention perf worlds)."""
    pids, p = set(), os.getpid()
    while p > 1 and p not in pids:
        pids.add(p)
        try:
            p = _ppid(p)
        except (OSError, ValueError, IndexError):
            break
    return pids


def machine_state() -> dict:
    """Load average and counts of other agents' heavy processes (perf-benchmark scripts, gz servers)."""
    st = {}
    try:
        st["loadavg"] = open("/proc/loadavg").read().split()[:3]
    except OSError:
        pass
    try:
        out = subprocess.run(["ps", "-eo", "pid=,args="], capture_output=True, text=True, timeout=10).stdout
        mine = _own_lineage()
        rows = []
        for ln in out.splitlines():
            pid, _, args = ln.strip().partition(" ")
            if pid.isdigit() and int(pid) not in mine:
                rows.append(args)
        st["perf_benchmark_procs"] = sum(1 for a in rows if re.search(r"/experiments/perf/(scripts|launch)/", a)
                                         and "tail " not in a[:8])
        st["other_gz_sim_procs"] = sum(1 for a in rows if re.search(r"\bgz sim\b", a))
    except Exception:  # noqa: BLE001
        pass
    return st


