class GpuSampler:
    """nvidia-smi -lms sampling (whole GPU, includes the Windows desktop)."""

    def __init__(self, period_ms: int = 500):
        self.samples: list[tuple] = []
        self.ok = os.path.exists(NVSMI)
        self.p = None
        if not self.ok:
            return
        try:
            self.p = subprocess.Popen([NVSMI, "--query-gpu=utilization.gpu,memory.used,clocks.sm,power.draw",
                                       "--format=csv,noheader,nounits", f"-lms={period_ms}"],
                                      stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True)
        except OSError:
            self.ok = False
            return
        threading.Thread(target=self._run, daemon=True).start()

    def _run(self) -> None:
        for line in self.p.stdout:
            try:
                vals = [float(v) if v.strip() not in ("[N/A]", "N/A") else float("nan") for v in line.strip().split(",")]
                self.samples.append((clock(), *vals))
            except ValueError:
                pass

    def between(self, a: float, b: float) -> list[tuple]:
        return [s for s in self.samples if a <= s[0] <= b]

    def stop(self) -> None:
        if self.p is None:
            return
        try:
            self.p.terminate()
            self.p.wait(timeout=3)
        except Exception:  # noqa: BLE001
            try:
                self.p.kill()
            except Exception:  # noqa: BLE001
                pass


def gpu_summary(s: list[tuple]) -> dict | None:
    if not s:
        return None
    a = np.array(s, dtype=np.float64)
    return {"n": len(s), "util_mean": round(float(np.nanmean(a[:, 1])), 1), "util_max": float(np.nanmax(a[:, 1])),
            "mem_mean_mib": round(float(np.nanmean(a[:, 2])), 0), "mem_max_mib": float(np.nanmax(a[:, 2])),
            "sm_clock_mean": round(float(np.nanmean(a[:, 3])), 0), "power_mean_w": round(float(np.nanmean(a[:, 4])), 1)}


