def _abs_uri(text: str, base: Path) -> str:
    t = text.strip()
    if not t or t.startswith(("/", "model://", "http://", "https://", "file://", "package://")):
        return t
    return str((base / t).resolve())


def lidar_model_xml(name: str, pose: tuple, topic: str, preset: dict, rate: float | None = None) -> ET.Element:
    """A static model with one gpu_lidar at its link origin."""
    p = preset
    x, y, z, roll, pitch, yaw = pose
    m = ET.Element("model", {"name": name})
    ET.SubElement(m, "static").text = "true"
    ET.SubElement(m, "pose").text = f"{x:.6f} {y:.6f} {z:.6f} {roll:.6f} {pitch:.6f} {yaw:.6f}"
    link = ET.SubElement(m, "link", {"name": "link"})
    s = ET.SubElement(link, "sensor", {"name": "lidar", "type": "gpu_lidar"})
    ET.SubElement(s, "topic").text = topic
    ET.SubElement(s, "update_rate").text = f"{rate or p['rate']:g}"
    ET.SubElement(s, "always_on").text = "1"
    ET.SubElement(s, "visualize").text = "false"
    lid = ET.SubElement(s, "lidar")
    scan = ET.SubElement(lid, "scan")
    for tag, n, lo, hi in (("horizontal", p["hs"], p["hmin"], p["hmax"]), ("vertical", p["vs"], p["vmin"], p["vmax"])):
        e = ET.SubElement(scan, tag)
        ET.SubElement(e, "samples").text = str(int(n))
        ET.SubElement(e, "resolution").text = "1"
        ET.SubElement(e, "min_angle").text = repr(float(lo))
        ET.SubElement(e, "max_angle").text = repr(float(hi))
    rg = ET.SubElement(lid, "range")
    ET.SubElement(rg, "min").text = f"{p['rmin']:g}"
    ET.SubElement(rg, "max").text = f"{p['rmax']:g}"
    ET.SubElement(rg, "resolution").text = "0.01"
    return m


def prepare_world(sdf_in: str | Path, sdf_out: str | Path, lidars: list[dict], *, strip_lidars: bool = False,
                  ensure_sensors: bool = True, gravity: str | None = None, remove_models: list[str] | None = None,
                  extra_models_xml: list[str] | None = None) -> dict:
    """Write a benchmark copy of ``sdf_in`` (see module docstring); returns facts about the edit.

    ``lidars``: [{"name", "pose": (x, y, z, roll, pitch, yaw), "topic", "preset": dict, "rate"}].
    """
    sdf_in = Path(sdf_in).resolve()
    tree = ET.parse(sdf_in)
    root = tree.getroot()
    world = root.find("world")
    if world is None:
        raise ValueError(f"{sdf_in}: no <world>")
    base = sdf_in.parent
    n_rew = 0
    for el in root.iter():
        if el.tag in URI_TAGS and el.text:
            new = _abs_uri(el.text, base)
            if new != el.text.strip():
                el.text = new
                n_rew += 1
    for eng in root.iter("engine"):
        fn = eng.find("filename")
        if fn is not None and fn.text and fn.text.strip().startswith(("./", "../")):
            fn.text = str((base / fn.text.strip()).resolve())
            n_rew += 1
    facts = {"source": str(sdf_in), "copy": str(sdf_out), "world_name": world.get("name"), "uris_rewritten": n_rew}
    plugins = world.findall("plugin")
    has_sensors = any("sensors-system" in (p.get("filename") or "") for p in plugins)
    facts["had_sensors_system"] = has_sensors
    if ensure_sensors and not has_sensors:
        pl = ET.Element("plugin", {"name": "gz::sim::systems::Sensors", "filename": "gz-sim-sensors-system"})
        ET.SubElement(pl, "render_engine").text = "ogre2"
        idx = list(world).index(plugins[-1]) + 1 if plugins else 0
        world.insert(idx, pl)
        facts["added_sensors_system"] = True
    stripped = []
    if strip_lidars:
        doomed = [(parent, s) for parent in world.iter() for s in parent.findall("sensor")
                  if s.get("type") in ("gpu_lidar", "gpu_ray", "lidar", "ray")]
        for parent, s in doomed:   # removed after the walk (never mutate a tree while iterating it)
            parent.remove(s)
            stripped.append(s.get("name"))
    facts["stripped_lidars"] = stripped
    removed = []
    for name in remove_models or []:
        for m in list(world.findall("model")):
            if m.get("name") == name:
                world.remove(m)
                removed.append(name)
    facts["removed_models"] = removed
    if gravity is not None:
        g = world.find("gravity")
        if g is None:
            g = ET.SubElement(world, "gravity")
        g.text = gravity
        facts["gravity"] = gravity
    for L in lidars:
        world.append(lidar_model_xml(L["name"], tuple(L["pose"]), L["topic"], L["preset"], L.get("rate")))
    for xml in extra_models_xml or []:
        world.append(ET.fromstring(xml))
    Path(sdf_out).parent.mkdir(parents=True, exist_ok=True)
    tree.write(sdf_out, encoding="unicode", xml_declaration=True)
    facts["n_lidars"] = len(lidars)
    return facts


