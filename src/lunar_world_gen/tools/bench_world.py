"""Benchmark a world SDF headless in Gazebo Harmonic with injected static gpu_lidar sensors.

Run with the SYSTEM python3 (it has the gz-transport13 / gz-msgs10 bindings), from WSL:

    /usr/bin/python3 tools/bench_world.py WORLD.sdf --out RESULT.json \
        [--pose-agl X,Y,H[,YAW]]... [--pose X,Y,Z[,YAW]]... [--lidar real|robinw] \
        [--window 30] [--warmup 5] [--load-timeout 300] [--strip-existing-lidars] [--config CFG]

What it does (docs/DESIGN.md section 13, "Gazebo, world only"):
  1. writes a temporary copy of the SDF next to the output: relative URIs made absolute,
     the Sensors system (ogre2) added if the world lacks it (generated worlds leave it to the
     robot), optionally existing gpu_lidar sensors removed, and one static gpu_lidar model per
     pose injected (topics /validation/lidar_<k>, points on /validation/lidar_<k>/points);
  2. starts ``timeout -s KILL LIMIT gz sim -s -r --headless-rendering -v 4 COPY`` in
     its own session (setsid) with the WSL GPU environment (GALLIUM_DRIVER=d3d12, ...), its own
     GZ_PARTITION / ROS_DOMAIN_ID and a private ROS_HOME; the server log is time-stamped;
  3. measures: load time (start -> first LiDAR message, plus first /stats, sim running and the
     log phases), mean RTF over the window (sim/real from /world/<w>/stats and sim/wall),
     LiDAR message rates, server CPU % (100 % = one core), RSS / peak RSS, GPU utilisation and
     memory via /usr/lib/wsl/lib/nvidia-smi (whole GPU, idle baseline first), the renderer
     from /proc/<pid>/maps (libd3d12 = GPU, llvmpipe/swrast = software), and [Err]/[Wrn] lines
     in the server log before shutdown;
  4. always stops the process group with SIGKILL (never SIGTERM/SIGINT: gz sim segfaults when it is
     asked to shut down, and WSL then writes a 1.5-3.6 GB crash dump to %TEMP%\\wsl-crashes) and
     writes the JSON result with pass/fail against config ``validation`` (load_time_max_s, rtf_min,
     server_rss_max_gb). The ``timeout`` wrapper also uses SIGKILL for the whole group.

The helpers (SDF injection, GzServer, /proc probes, cloud decoding) are reused by
tools/lidar_capture.py.
"""
