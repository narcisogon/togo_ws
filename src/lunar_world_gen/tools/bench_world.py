def build_ground_fn(config: str | None):
    """h(x, y) from the generator build of ``config``: a single core grid if there is one, else the
    final per-tile core heights (``heights/tile_ii_jj``: H0 + fillets, what the visual ground TIN
    approximates to 5 mm), else the H0 tiles; outside the core the ring grid. Returns (fn, info)."""
    from lunar_world_gen.config import load_config
    from lunar_world_gen.validate.lidar_checks import build_height_sources, point_height_fn
    cfg = load_config(config) if config else load_config()
    sources, found = build_height_sources(cfg)
    info = {"config": str(cfg["_source"]["config_file"]), "build_dir": found.get("build_dir"),
            "sources": [{"name": n, "n_grids": len(p), "first": p[0]} for n, p in sources]}
    return (point_height_fn(sources) if sources else None), info


def ground_height_fn(grid_prefix: str | None = None, sdf: str | None = None, config: str | None = None,
                     info: dict | None = None):
    """Return h(x, y) -> float from a Grid (bilinear), from the SDF's static visual GLB meshes, or
    from the generator build named by ``config`` (see ``build_ground_fn``); ``info`` gets the source."""
    info = {} if info is None else info
    if grid_prefix:
        info["ground_source"] = f"grid {grid_prefix}"
    elif sdf:
        info["ground_source"] = f"visual GLB meshes of {sdf}"
    elif config is not None:
        fn, binfo = build_ground_fn(config or None)
        info["ground_source"] = "generator build height grids"
        info["ground_sources"] = binfo
        return fn
    if grid_prefix:
        from lunar_world_gen.grid import Grid
        g = Grid.load(grid_prefix, mmap=True)

        def h(x, y):
            if not bool(g.contains(np.array([x]), np.array([y]))[0]):
                return float("nan")
            return float(g.sample(np.array([x]), np.array([y]), order=1)[0])
        return h
    if sdf:
        from lunar_world_gen.validate.lidar_checks import sdf_visual_meshes
        from lunar_world_gen.validate.static_checks import MeshHeightField
        mh = MeshHeightField(sdf_visual_meshes(sdf))

        def h(x, y):
            return float(mh.height(np.array([x]), np.array([y]))[0])
        return h
    return None


def parse_pose(text: str, n_min: int = 3) -> tuple[float, ...]:
    v = [float(t) for t in text.replace(" ", ",").split(",") if t != ""]
    if len(v) < n_min:
        raise ValueError(f"pose {text!r} needs at least {n_min} numbers")
    return tuple(v)


def resolve_poses(poses_abs: list[str], poses_agl: list[str], height_fn, default_agl: float) -> list[dict]:
    """Absolute poses x,y,z[,yaw] and above-ground poses x,y,h[,yaw] -> sensor poses (6-DoF)."""
    out = []
    for p in poses_abs:
        v = parse_pose(p)
        out.append({"pose": (v[0], v[1], v[2], 0.0, 0.0, v[3] if len(v) > 3 else 0.0), "request": list(v),
                    "ground_z": None, "mode": "absolute"})
    for p in poses_agl:
        v = parse_pose(p)
        gz_ = height_fn(v[0], v[1]) if height_fn else float("nan")
        if not math.isfinite(gz_):
            gz_ = 0.0
            mode = "agl_no_ground_assumed_0"
        else:
            mode = "agl"
        out.append({"pose": (v[0], v[1], gz_ + v[2], 0.0, 0.0, v[3] if len(v) > 3 else 0.0),
                    "request": list(v), "ground_z": gz_, "mode": mode})
    if not out:
        gz_ = height_fn(0.0, 0.0) if height_fn else float("nan")
        gz_ = gz_ if math.isfinite(gz_) else 0.0
        out.append({"pose": (0.0, 0.0, gz_ + default_agl, 0.0, 0.0, 0.0), "request": [0.0, 0.0, default_agl, 0.0],
                    "ground_z": gz_, "mode": "default"})
    return out


def load_thresholds(config: str | None) -> dict:
    th = {"load_time_max_s": 30.0, "rtf_min": 0.95, "server_rss_max_gb": 5.0}
    try:
        from lunar_world_gen.config import load_config
        cfg = load_config(config) if config else load_config()
        v = cfg.get("validation") or {}
        for k in th:
            if k in v:
                th[k] = float(v[k])
        th["source"] = str(cfg["_source"]["config_file"])
    except Exception as e:  # noqa: BLE001
        th["source"] = f"defaults ({e})"
    return th


def wait_until_idle(max_wait_min: float, poll_s: float = 60.0) -> dict:
    """Wait (bounded) while perf-benchmark processes run; returns what was observed."""
    t0 = clock()
    st = machine_state()
    while st.get("perf_benchmark_procs", 0) > 0 and clock() - t0 < max_wait_min * 60:
        time.sleep(poll_s)
        st = machine_state()
    st["waited_s"] = round(clock() - t0, 1)
    return st


