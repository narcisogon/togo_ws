def gz_env(partition: str, domain: int, ros_home: str | Path, display: bool = False) -> dict:
    env = dict(os.environ)
    env.update({"GZ_PARTITION": partition, "ROS_DOMAIN_ID": str(domain), "ROS_HOME": str(ros_home),
                "GALLIUM_DRIVER": "d3d12", "MESA_D3D12_DEFAULT_ADAPTER_NAME": "NVIDIA"})
    # Mesa d3d12 leaks one command signature per indirect draw (docs/impl/leak_diagnosis.md): hide the extension so
    # Ogre-Next uses plain draws. A value already set (even empty, for an A/B run) is kept.
    env.setdefault("MESA_EXTENSION_OVERRIDE", "-GL_ARB_multi_draw_indirect")
    ld = env.get("LD_LIBRARY_PATH", "")
    if "/usr/lib/wsl/lib" not in ld.split(":"):
        env["LD_LIBRARY_PATH"] = "/usr/lib/wsl/lib" + (":" + ld if ld else "")
    if display:
        env.update({"DISPLAY": ":0", "WAYLAND_DISPLAY": "wayland-0", "XDG_RUNTIME_DIR": "/mnt/wslg/runtime-dir"})
    Path(ros_home).mkdir(parents=True, exist_ok=True)
    return env


class GzServer:
    """``gz sim -s`` in its own session; time-stamped log; phase/error scanning; group stop."""

    def __init__(self, world: str | Path, log_path: str | Path, env: dict, limit_s: int = 600,
                 headless_rendering: bool = True, verbosity: int = 4):
        self.world = str(world)
        self.log_path = Path(log_path)
        self.env = env
        self.limit_s = int(limit_s)
        # no --foreground: at the limit timeout SIGKILLs the child AND its whole process group (gz
        # must never get SIGTERM/SIGINT, see stop())
        self.cmd = ["timeout", "-s", "KILL", str(self.limit_s), "stdbuf", "-oL", "-eL",
                    "gz", "sim", "-s", "-r"] + (["--headless-rendering"] if headless_rendering else []) + \
                   ["-v", str(verbosity), self.world]
        self.proc: subprocess.Popen | None = None
        self.pgid: int | None = None
        self.t0 = 0.0                # monotonic clock() at start; every time below is relative to it
        self.t0_wall = 0.0
        self.phases: dict[str, float] = {}
        self.errors: list[tuple[float, str]] = []
        self.warnings: list[tuple[float, str]] = []
        self.stop_requested_at: float | None = None
        self._reader: threading.Thread | None = None
        self.server_pid: int | None = None

    def start(self) -> None:
        self.log_path.parent.mkdir(parents=True, exist_ok=True)
        self.t0 = clock()
        self.t0_wall = time.time()
        self.proc = subprocess.Popen(self.cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                     stdin=subprocess.DEVNULL, env=self.env, start_new_session=True)
        self.pgid = self.proc.pid
        (self.log_path.parent / "pgid.txt").write_text(f"{self.pgid}\n")
        self._reader = threading.Thread(target=self._read, daemon=True)
        self._reader.start()

    def _read(self) -> None:
        with open(self.log_path, "w", errors="replace") as log:
            log.write(f"# t0_wall={self.t0_wall:.6f} (times below: monotonic s since start) "
                      f"cmd={' '.join(shlex.quote(c) for c in self.cmd)}\n")
            for raw in self.proc.stdout:
                t = clock() - self.t0
                line = ANSI.sub("", raw.decode("utf-8", "replace")).rstrip("\n")
                log.write(f"{t:9.3f} {line}\n")
                log.flush()
                for k, pat in LOG_PHASES.items():
                    if k not in self.phases and pat in line:
                        self.phases[k] = round(t, 3)
                before_stop = self.stop_requested_at is None
                if "[Err]" in line and before_stop:
                    self.errors.append((round(t, 3), line.strip()[:400]))
                elif "[Wrn]" in line and before_stop:
                    self.warnings.append((round(t, 3), line.strip()[:400]))

    def alive(self) -> bool:
        return bool(self.pgid) and bool(group_pids(self.pgid))

    def find_server_pid(self) -> int | None:
        if self.pgid is None:
            return None
        if self.server_pid and os.path.exists(f"/proc/{self.server_pid}"):
            return self.server_pid
        cands = [(p, c) for p, c in group_pids(self.pgid) if c not in ("timeout", "stdbuf", "bash", "sh")]
        if cands:
            self.server_pid = max(cands, key=lambda pc: mem_status(pc[0]).get("VmRSS", 0))[0]
        return self.server_pid

    def stop(self, wait_s: float = 15.0) -> dict:
        """SIGKILL the whole process group directly; never touches other process groups.

        gz sim segfaults when it shuts down on SIGTERM/SIGINT, and WSL then writes a 1.5-3.6 GB
        crash dump (``%TEMP%\\wsl-crashes``), so the server is never asked to shut down. This group
        holds only the timeout wrapper and the server (no ROS nodes)."""
        info: dict = {"pgid": self.pgid, "signal": "SIGKILL"}
        if self.pgid is None:
            return info
        self.stop_requested_at = clock() - self.t0
        info["sent"] = kill_group(self.pgid, signal.SIGKILL)
        try:
            self.proc.wait(timeout=10)
        except Exception:  # noqa: BLE001
            pass
        tg = clock()
        while group_pids(self.pgid, include_zombies=True) and clock() - tg < wait_s:
            time.sleep(0.25)
        if self._reader is not None:
            self._reader.join(timeout=5)
        info["remaining_in_group"] = len(group_pids(self.pgid, include_zombies=True))
        info["stopped_after_s"] = round(clock() - self.t0, 2)
        return info

    def log_summary(self, max_lines: int = 20) -> dict:
        errs = []
        seen = set()
        for t, ln in self.errors:
            key = re.sub(r"\d+", "#", ln)
            if key not in seen:
                seen.add(key)
                errs.append(f"{t:.2f}s {ln}")
        warns, wseen = [], set()
        n_harmless = 0
        for t, ln in self.warnings:
            if any(h in ln for h in HARMLESS_WARN):
                n_harmless += 1
                continue
            key = re.sub(r"\d+", "#", ln)
            if key not in wseen:
                wseen.add(key)
                warns.append(f"{t:.2f}s {ln}")
        return {"n_err": len(self.errors), "n_wrn": len(self.warnings), "n_wrn_harmless": n_harmless,
                "errors": errs[:max_lines], "warnings": warns[:max_lines], "phases_s": dict(self.phases)}


