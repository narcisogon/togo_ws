NP_DT = {0: "i1", 1: "u1", 2: "<i2", 3: "<u2", 4: "<i4", 5: "<u4", 6: "<f4", 7: "<f8"}


def decode_cloud(msg) -> dict:
    """PointCloudPacked -> dict of (height, width) arrays per field (gzcap.py logic)."""
    names, fmts, offs = [], [], []
    for f in msg.field:
        names.append(f.name)
        fmts.append(NP_DT[f.datatype])
        offs.append(f.offset)
    dt = np.dtype({"names": names, "formats": fmts, "offsets": offs, "itemsize": msg.point_step})
    n = msg.width * msg.height
    arr = np.frombuffer(msg.data, dtype=dt, count=n)
    return {k: np.array(arr[k]).reshape(msg.height, msg.width) for k in names}


def stamp_of(header) -> float:
    return header.stamp.sec + 1e-9 * header.stamp.nsec


class Watcher:
    """Subscribes to /world/<w>/stats and LiDAR point topics; keeps timings and (optionally) clouds."""

    def __init__(self, world_name: str, lidar_topics: list[str], keep_clouds: int = 0, skip_clouds: int = 1):
        from gz.msgs10.pointcloud_packed_pb2 import PointCloudPacked
        from gz.msgs10.world_stats_pb2 import WorldStatistics
        from gz.transport13 import Node
        self.lock = threading.Lock()
        self.stats: list[tuple] = []        # wall, sim, real, iterations, rtf
        self.first_stats: float | None = None
        self.lidar: dict[str, list[tuple]] = {t: [] for t in lidar_topics}   # wall, stamp, finite
        self.first_lidar: dict[str, float] = {}
        self.clouds: dict[str, list[dict]] = {t: [] for t in lidar_topics}
        self.keep, self.skip = keep_clouds, skip_clouds
        self.node = Node()
        self.node.subscribe(WorldStatistics, f"/world/{world_name}/stats", self._on_stats)
        for t in lidar_topics:
            self.node.subscribe(PointCloudPacked, t, self._make_cb(t))

    def _on_stats(self, msg) -> None:
        w = clock()
        with self.lock:
            if self.first_stats is None:
                self.first_stats = w
            self.stats.append((w, msg.sim_time.sec + 1e-9 * msg.sim_time.nsec,
                               msg.real_time.sec + 1e-9 * msg.real_time.nsec, int(msg.iterations),
                               float(msg.real_time_factor)))

    def _make_cb(self, topic: str):
        def cb(msg) -> None:
            w = clock()
            st = stamp_of(msg.header)
            keep = False
            with self.lock:
                if topic not in self.first_lidar:
                    self.first_lidar[topic] = w
                n_seen = len(self.lidar[topic]) + 1
                keep = n_seen > self.skip and len(self.clouds[topic]) < self.keep
            d = None
            finite = None
            if keep or n_seen <= 3:
                d = decode_cloud(msg)
                finite = int(np.isfinite(d["x"]).sum())
            with self.lock:
                self.lidar[topic].append((w, st, finite, msg.width * msg.height))
                if keep and d is not None:
                    frame = ""
                    for hd in msg.header.data:
                        if hd.key == "frame_id" and hd.value:
                            frame = hd.value[0]
                    self.clouds[topic].append({"data": d, "stamp": st, "frame": frame, "width": msg.width,
                                               "height": msg.height, "wall": w})
        return cb

    def sim_running_since(self, threshold: float = 0.1) -> float | None:
        with self.lock:
            for w, sim, *_ in self.stats:
                if sim > threshold:
                    return w
        return None


